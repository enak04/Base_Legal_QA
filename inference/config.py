def get_required_files(config: dict | None = None) -> list[dict]:
    """
    Return the files a LegalQAEngine needs, with their paths and descriptions.

    Pass the engine's own config so each mode (actionable / informative / readable)
    is checked against its own directory; without it the default config is used.
    """
    cfg = config or INFERENCE_CONFIG
    spec = [
        ("rl_model_path", "Trained PPO RL policy model (generated by train_rl.py)"),
        ("dssm_model_path", "Trained DSSM retrieval model (generated by train_dssm.py)"),
        ("retrieval_index", "Pre-computed retrieval embeddings and DB data (generated by train_dssm.py)"),
        ("node_emb_cache_path", "Pre-computed BERT embeddings for KG nodes (generated during training)"),
        ("kg_path", "Hierarchical Knowledge Graph edge list"),
        ("nodes_csv_path", "KG node metadata (used for seed chain discovery via TF-IDF)"),
    ]
    return [
        {"path": cfg[key], "name": os.path.basename(cfg[key]), "description": desc}
        for key, desc in spec
    ]
